async function testServer() {
  const python = 'C:\\Users\\Sofya\\.cache\\codex-runtimes\\codex-primary-runtime\\dependencies\\python\\python.exe';
  const child = spawn(python,[path.join(__dirname,'test_browser_server.py')],{cwd:__dirname,windowsHide:true,stdio:['ignore','pipe','pipe']});
  let output='',errors=''; child.stderr.on('data', chunk => errors += chunk);
  const info = await new Promise((resolve,reject) => {
    const timeout = setTimeout(() => {child.kill();reject(new Error('Test server startup timeout: '+errors));},15000);
    child.on('error', error => {clearTimeout(timeout);reject(error);});
    child.on('exit', () => {clearTimeout(timeout);reject(new Error('Test server exited: '+errors));});
    child.stdout.on('data', chunk => {output+=chunk;if(output.includes('\n')){clearTimeout(timeout);resolve(JSON.parse(output.split('\n')[0]));}});
  });
  return {...info,child};
}

